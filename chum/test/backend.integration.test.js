import test from 'node:test';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createServer} from 'vite';
import {createChumbucketClient} from '../src/chumbucket.js';

const backendSource=path.resolve(process.env.CHUM_BACKEND_SOURCE||'../chumbucket/src/app.js');
test('frontend adapter and Vite proxy integrate with Chumbucket', {skip:!existsSync(backendSource)}, async t=>{
 const {createApp}=await import(pathToFileURL(backendSource));
 const directory=await mkdtemp(path.join(tmpdir(),'chum-frontend-test-'));
 const password='chum-integration-only-password';
 const app=await createApp({dataDir:directory,adminPassword:password,origin:'http://localhost:3001',secure:false});
 let vite;
 t.after(async()=>{if(vite)await vite.close();await app.close();assert.equal(path.dirname(directory),path.resolve(tmpdir()));await rm(directory,{recursive:true,force:true});});
 await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
 process.env.CHUM_BACKEND_TARGET=`http://127.0.0.1:${app.server.address().port}`;
 process.env.CHUM_FRONTEND_PORT='5179';
 vite=await createServer({configFile:path.resolve('vite.config.js'),server:{host:'127.0.0.1'},logLevel:'error'});
 await vite.listen();
 const base='http://127.0.0.1:5179';
 const client=()=>{
  let cookie='';
  const fetcher=async(url,options={})=>{
   const response=await fetch(url,{...options,headers:{...options.headers,Origin:base,...(cookie?{Cookie:cookie}:{})}});
   const updated=response.headers.get('set-cookie');if(updated)cookie=updated.split(';')[0];
   return response;
  };
  return {api:createChumbucketClient(base,fetcher),fetch:fetcher,cookie:()=>cookie};
 };
 const admin=client(),guest=client();
 assert.equal((await fetch(base)).status,200);
 assert.equal((await fetch(`${base}/api/health`)).status,200);
 await assert.rejects(admin.api.session(),e=>e.status===401);
 await admin.api.login(password);
 assert.equal((await admin.api.session()).user.role,'admin');
 const listing=await admin.api.list('root');assert.deepEqual(listing.tree,[]);
 const {item:folder}=await admin.api.mkdir('root','Test & friends');
 const {item:nested}=await admin.api.mkdir(folder.id,'Nested');
 const {item:file}=await admin.api.upload(nested.id,new File(['hello, chum!'],'hello & chum.txt',{type:'text/plain'}));
 assert.equal(file.size,12);
 await admin.api.update(file.id,{frozen:true});
 assert.equal((await admin.api.list(folder.id)).tree.find(x=>x.id===file.id).frozen,true);
 await admin.api.update(file.id,{frozen:false,name:'renamed.txt'});
 await admin.api.checkDownload(file.id);
 assert.equal(await(await admin.fetch(admin.api.downloadUrl(file.id))).text(),'hello, chum!');
 const {settings}=await admin.api.saveSettings({domain:base,hours:6});
 assert.deepEqual(settings,{domain:base,hours:6});
 const {link}=await admin.api.invite(folder.id,6);
 assert.equal((await admin.api.links()).links.length,1);
 await guest.api.login(link.passphrase);
 assert.equal((await guest.api.session()).user.root,folder.id);
 await assert.rejects(guest.api.list('root'),e=>e.status===404);
 await assert.rejects(guest.api.remove(file.id),e=>e.status===403);
 assert.equal((await guest.api.list(folder.id)).tree.some(x=>x.id===file.id),true);
 const {item:owned}=await guest.api.upload(folder.id,new File(['a chum uploaded this'],'guest.txt'));
 await guest.api.update(owned.id,{name:'guest renamed.txt'});
 await guest.api.remove(owned.id);
 await guest.api.logout();
 await assert.rejects(guest.api.session(),e=>e.status===401);
 // Follow a token invitation as a browser: exchange cookie then follow the 303.
 const exchanged=await fetch(`${base}/?other=yes&access=${link.token}`,{redirect:'manual'});
 assert.equal(exchanged.status,303);
 assert.equal(exchanged.headers.get('location'),'/');
 assert.match(exchanged.headers.get('set-cookie'),/HttpOnly/);
 const tokenCookie=exchanged.headers.get('set-cookie').split(';')[0];
 assert.equal((await(await fetch(`${base}/api/session`,{headers:{Cookie:tokenCookie}})).json()).user.root,folder.id);
 await admin.api.revoke(link.id);
 const revoked=await fetch(`${base}/api/session`,{headers:{Cookie:tokenCookie}});
 assert.equal(revoked.status,401);
 assert.equal((await admin.api.links()).links[0].revoked,true);
 // The local proxy translates trusted origins, rejects hostile ones and leaves CSRF active.
 const hostile=await fetch(`${base}/api/session`,{method:'POST',headers:{Origin:'https://untrusted.example','X-Chum-Request':'1','Content-Type':'application/json'},body:JSON.stringify({passphrase:password})});
 assert.equal(hostile.status,403);
 assert.equal((await hostile.json()).error,'Frontend origin rejected.');
 const noCsrf=await fetch(`${base}/api/folders`,{method:'POST',headers:{Origin:base,Cookie:admin.cookie(),'X-Chum-Request':'1','Content-Type':'application/json'},body:JSON.stringify({name:'Must be rejected'})});
 assert.equal(noCsrf.status,403);
 await admin.api.remove(folder.id);
 assert.deepEqual((await admin.api.list('root')).tree,[]);
 await admin.api.logout();
 await assert.rejects(admin.api.session(),e=>e.status===401);
});
